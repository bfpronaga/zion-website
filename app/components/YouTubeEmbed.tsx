'use client';

import { useState } from 'react';
import Image from 'next/image';

interface YouTubeEmbedProps {
  videoId: string;
  title?: string;
  badge?: string;
  autoplay?: boolean;
  showTitle?: boolean;
}

/**
 * YouTubeEmbed Component
 * 
 * Displays a YouTube video with automatic thumbnail loading.
 * Thumbnails are fetched dynamically from YouTube's servers - no manual downloads needed!
 * 
 * Features:
 * - Auto-loads thumbnail from YouTube
 * - Click to play (lite embed for performance)
 * - Responsive sizing
 * - Optional title and badge
 * 
 * @param videoId - YouTube video ID (e.g., "JMOkQ8ZGtCI")
 * @param title - Optional video title
 * @param badge - Optional badge text (e.g., "NEW", "教育コンテンツ")
 * @param autoplay - Whether to autoplay when clicked (default: true)
 * @param showTitle - Whether to show title below video (default: true)
 */
export default function YouTubeEmbed({
  videoId,
  title = '',
  badge = '',
  autoplay = true,
  showTitle = true,
}: YouTubeEmbedProps) {
  const [isLoaded, setIsLoaded] = useState(false);

  // YouTube thumbnail URLs (automatically generated by YouTube)
  // Try maxres first, fallback to hq if not available
  const thumbnailUrl = `https://img.youtube.com/vi/${videoId}/maxresdefault.jpg`;
  const thumbnailFallback = `https://img.youtube.com/vi/${videoId}/hqdefault.jpg`;

  const embedUrl = `https://www.youtube.com/embed/${videoId}${autoplay ? '?autoplay=1' : ''}`;
  const watchUrl = `https://www.youtube.com/watch?v=${videoId}`;

  const handleClick = () => {
    setIsLoaded(true);
  };

  return (
    <div className="video-card">
      <div className="video-wrapper">
        {!isLoaded ? (
          // Thumbnail view (before clicking play)
          <button
            onClick={handleClick}
            className="video-thumbnail-button"
            aria-label={`Play ${title || 'video'}`}
            style={{
              position: 'relative',
              width: '100%',
              height: '100%',
              border: 'none',
              padding: 0,
              background: 'none',
              cursor: 'pointer',
            }}
          >
            {/* YouTube thumbnail - auto-fetched */}
            <Image
              src={thumbnailUrl}
              alt={title || 'YouTube video thumbnail'}
              fill
              style={{ objectFit: 'cover' }}
              onError={(e) => {
                // Fallback to lower quality if maxres not available
                const img = e.target as HTMLImageElement;
                img.src = thumbnailFallback;
              }}
            />
            
            {/* Play button overlay */}
            <div
              style={{
                position: 'absolute',
                top: '50%',
                left: '50%',
                transform: 'translate(-50%, -50%)',
                width: '68px',
                height: '48px',
                backgroundColor: 'rgba(255, 0, 0, 0.9)',
                borderRadius: '12px',
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
                transition: 'all 0.2s ease',
              }}
              className="play-button"
            >
              <svg
                width="24"
                height="24"
                viewBox="0 0 24 24"
                fill="white"
                style={{ marginLeft: '2px' }}
              >
                <path d="M8 5v14l11-7z" />
              </svg>
            </div>

            <style jsx>{`
              .play-button:hover {
                background-color: rgba(255, 0, 0, 1) !important;
                transform: translate(-50%, -50%) scale(1.1) !important;
              }
            `}</style>
          </button>
        ) : (
          // Embedded iframe (after clicking play)
          <iframe
            src={embedUrl}
            title={title || 'YouTube video'}
            frameBorder="0"
            allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture"
            allowFullScreen
            style={{
              position: 'absolute',
              top: 0,
              left: 0,
              width: '100%',
              height: '100%',
            }}
          />
        )}
      </div>
      
      {/* Video info section */}
      {showTitle && (title || badge) && (
        <div className="video-info">
          {badge && <span className="video-badge">{badge}</span>}
          {title && <h3 className="video-title">{title}</h3>}
          {!isLoaded && (
            <a
              href={watchUrl}
              target="_blank"
              rel="noopener noreferrer"
              className="video-link"
              onClick={(e) => e.preventDefault()}
              style={{
                fontSize: '0.85rem',
                color: 'var(--accent-blue)',
                textDecoration: 'none',
                display: 'inline-flex',
                alignItems: 'center',
                gap: '0.25rem',
                marginTop: '0.5rem',
              }}
            >
              YouTube で見る
              <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                <path d="M18 13v6a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h6M15 3h6v6M10 14L21 3" />
              </svg>
            </a>
          )}
        </div>
      )}
    </div>
  );
}
